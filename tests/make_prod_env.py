#!/usr/bin/env python3
"""Write .env.prod (the prod profile) and private/cloud.env (tests/load_cloud.sh) from the SurrealDB
Cloud values in a source env file. Prints only the key names it wrote, never a value.

usage: python3 -I tests/make_prod_env.py [source]   (default private/cloud-source.env:
       SURREAL_ENDPOINT, SURREAL_PASSWORD)
The database user, namespace and database are `books`.
"""
import os, sys
from urllib.parse import quote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
USER, NS, DB = "books", "books", "books"


def read(path):
    out = {}
    for line in open(path).read().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip().lower()] = v.strip().strip('"').strip("'")
    return out


def write(path, text):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(path, 0o600)


def main():
    src = read(os.path.join(ROOT, sys.argv[1] if len(sys.argv) > 1 else "private/cloud-source.env"))
    endpoint, password = src["surreal_endpoint"], src["surreal_password"]
    host = endpoint.split("://", 1)[-1].split("/", 1)[0]          # wss://host/rpc, https://host or host
    url = f"wss://{quote(USER, safe='')}:{quote(password, safe='')}@{host}/rpc?auth=database"
    write(os.path.join(ROOT, ".env.prod"),
          "# prod profile: SurrealDB Cloud (generated by tests/make_prod_env.py; never committed)\n"
          f"SECRET_SURREAL_URL={url}\nSURREAL_NS={NS}\nSURREAL_DB={DB}\n")
    os.makedirs(os.path.join(ROOT, "private"), mode=0o700, exist_ok=True)
    write(os.path.join(ROOT, "private", "cloud.env"),
          f"SURREAL_HTTP=https://{host}\nSURREAL_USER={USER}\nSURREAL_PASS={password}\nSURREAL_NS={NS}\nSURREAL_DB={DB}\n")
    print("wrote .env.prod: SECRET_SURREAL_URL SURREAL_NS SURREAL_DB")
    print("wrote private/cloud.env: SURREAL_HTTP SURREAL_USER SURREAL_PASS SURREAL_NS SURREAL_DB")


if __name__ == "__main__":
    main()
